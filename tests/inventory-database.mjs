import assert from "node:assert/strict";
import {readFile,readdir} from "node:fs/promises";
import {createInventoryRepository,validateInventory} from "../supabase/functions/three-k-api/inventory.js";
const {PGlite}=await import(process.env.PGLITE_MODULE || "@electric-sql/pglite");
const db=new PGlite();
function tagged(client){const sql=(strings,...values)=>client.query(strings.reduce((out,part,i)=>out+(i?`$${i}`:"")+part,""),values).then(result=>result.rows);sql.begin=callback=>db.transaction(tx=>callback(tagged(tx)));return sql;}
const owner={id:"00000000-0000-4000-8000-000000000001",role:"manager"},boss={id:"00000000-0000-4000-8000-000000000002",role:"rop"};
const repo=createInventoryRepository(async()=>tagged(db));
const rejected=(promise,status)=>assert.rejects(promise,error=>error.status===status);
try{
  await db.exec("create role anon;create role authenticated;create role service_role;create schema auth;create table auth.users(id uuid primary key);");
  const dir=new URL("../supabase/migrations/",import.meta.url),names=(await readdir(dir)).filter(n=>n.endsWith(".sql")).sort();
  for(const name of names)await db.exec(await readFile(new URL(name,dir),"utf8"));
  if(!names.some(n=>n.endsWith("_inventory.sql")))await db.exec(await readFile(new URL("../supabase/sql/inventory.sql",import.meta.url),"utf8"));
  await db.query("insert into auth.users values ($1),($2)",[owner.id,boss.id]);
  await db.query("insert into three_k.members(user_id,telegram_subject,display_name,role) values ($1,'one','Owner','manager'),($2,'two','Boss','rop')",[owner.id,boss.id]);
  await db.query("insert into three_k.deals(id,client,company,product,amount,assignee_id) values ('D-1','A','A','A',100,$1),('D-2','B','B','B',100,$2)",[owner.id,boss.id]);
  const data=validateInventory({name:"Sea-Doo",vin:"1HGCM82633A004352",price:"123.45",location:"Склад"}),request=crypto.randomUUID();
  await rejected(repo.create(data,request,owner),403);
  const item=await repo.create(data,request,boss);
  assert.equal((await repo.create(data,request,boss)).id,item.id);
  await rejected(repo.create(data,crypto.randomUUID(),boss),409);
  await rejected(repo.action(item.id,"reserve",{version:1,dealId:"D-2"},owner),403);
  const reserved=await repo.action(item.id,"reserve",{version:1,dealId:"D-1"},owner);
  assert.equal(reserved.status,"reserved");assert.equal(reserved.deal_id,"D-1");
  await rejected(repo.action(item.id,"reserve",{version:1,dealId:"D-2"},boss),409);
  await rejected(repo.update(item.id,data,2,boss),409);
  await rejected(repo.action(item.id,"deliver",{version:2},owner),409);
  const second=await repo.create({...data,vin:"",name:"Other"},crypto.randomUUID(),boss);
  await rejected(repo.action(second.id,"reserve",{version:1,dealId:"D-1"},owner),409);
  assert.equal((await repo.get(second.id)).status,"available");assert.equal((await repo.get(second.id)).events.length,1);
  const released=await repo.action(item.id,"release",{version:2},owner);
  assert.equal(released.deal_id,null);assert.equal(released.version,3);
  await repo.action(item.id,"archive",{version:3},boss);
  await rejected(repo.action(item.id,"reserve",{version:4,dealId:"D-1"},owner),409);
  await repo.action(item.id,"restore",{version:4},boss);
  await repo.update(item.id,{...data,location:"Шоурум"},5,boss);
  await rejected(repo.update(item.id,data,5,boss),409);
  await repo.action(item.id,"reserve",{version:6,dealId:"D-1"},owner);
  await db.query("update three_k.deals set stage='Успешно',status='closed' where id='D-1'");
  const sold=await repo.action(item.id,"deliver",{version:7},owner);
  assert.equal(sold.status,"sold");assert.equal(sold.deal_id,"D-1");
  await rejected(repo.action(item.id,"release",{version:8},owner),409);
  assert.equal((await repo.list({q:"Sea",status:"sold"})).items[0].id,item.id);
  assert.equal((await repo.list({dealId:"D-1"})).items.length,1);
  const grants=(await db.query("select has_table_privilege('anon','three_k.inventory','SELECT') as anon,has_table_privilege('authenticated','three_k.inventory','UPDATE') as authenticated")).rows[0];
  assert.deepEqual(grants,{anon:false,authenticated:false});
  console.log("Inventory PostgreSQL passed: create/retry, VIN uniqueness, role checks, double reservation, atomic rollback, archive/restore, version conflicts, release/delivery, deal links and private grants.");
}finally{await db.close();}
